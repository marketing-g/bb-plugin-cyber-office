export type MessageKey = keyof typeof messages;
type Value = string | number;
export type Translate = (key: MessageKey, ...values: Value[]) => string;
export function translator(language: Language): Translate {
 return (key, ...values) => messages[key][language === 'ru' ? 1 : 0].replace(/\{(\d+)\}/g, (token, i) => String(values[Number(i)] ?? token));
}
export const text = translator(DEFAULT_LANGUAGE);

export function quoteLines(value:string){return value.split(/\r\n|[\n\r\u2028\u2029]/).map(line=>'> '+line).join('\n');}

const dataKeys = new Map<string, MessageKey>((Object.keys(messages) as MessageKey[]).map(key=>[messages[key][1],key]));

/** Localize bundled data fields. Values outside the bundled dictionary are user content. */
export function dataText(language: Language, value: string): string {
 const key = dataKeys.get(value);
 return key ? translator(language)(key) : value;
}

type ChainStep = {id:string; title:string; role:string; output:string; needsUser:boolean; children?:ChainStep[]};
type ChainData = {blocks:{id:string; title:string; steps:ChainStep[]}[]};

export function localizeChains(data:ChainData,language:Language):ChainData {
 const step = (item:ChainStep):ChainStep => ({
  ...item, title:dataText(language,item.title), output:dataText(language,item.output),
  ...(item.children ? {children:item.children.map(step)} : {}),
 });
 return {blocks:data.blocks.map(block=>({...block,title:dataText(language,block.title),steps:block.steps.map(step)}))};
}
